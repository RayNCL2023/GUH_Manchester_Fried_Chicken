"""
Offline (not part of the submission): builds preflop_table.py, the
169x169 all-in equity table of every hand class against every other,
by Monte Carlo over random boards, on every CPU core.

    .venv/Scripts/python build_preflop.py [samples_per_pair]
"""

import multiprocessing
import random
import sys

import handeval as H


def _pair_equity(args):
    i, j, n, seed = args
    rng = random.Random(seed)
    ci, cj = H.CLASS_COMBOS[i], H.CLASS_COMBOS[j]
    ev = H.evaluate_ids
    total = 0.0
    done = 0
    deck = list(range(52))
    while done < n:
        a = ci[rng.randrange(len(ci))]
        b = cj[rng.randrange(len(cj))]
        if a[0] in b or a[1] in b:
            continue
        dead = {a[0], a[1], b[0], b[1]}
        board = []
        while len(board) < 5:
            c = deck[rng.randrange(52)]
            if c not in dead:
                dead.add(c)
                board.append(c)
        sa = ev([a[0], a[1]] + board)
        sb = ev([b[0], b[1]] + board)
        total += 1.0 if sa > sb else (0.5 if sa == sb else 0.0)
        done += 1
    return i, j, total / n


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 20000
    jobs = [(i, j, n, i * 1000 + j) for i in range(169) for j in range(i, 169)]
    eq = [[0.5] * 169 for _ in range(169)]
    with multiprocessing.Pool() as pool:
        for i, j, e in pool.imap_unordered(_pair_equity, jobs, chunksize=32):
            eq[i][j] = e
            eq[j][i] = 1.0 - e
    for i in range(169):
        eq[i][i] = 0.5
    # 4 hex digits per entry, value = round(eq * 65535), row-major.
    flat = "".join(
        "%04x" % round(eq[i][j] * 65535) for i in range(169) for j in range(169)
    )
    lines = [flat[k:k + 96] for k in range(0, len(flat), 96)]
    with open("preflop_table.py", "w") as out:
        out.write('"""Generated by build_preflop.py: 169x169 preflop all-in '
                  'equity, 4 hex digits per entry (/65535), row-major."""\n\n')
        out.write("EQUITY_HEX = (\n")
        for line in lines:
            out.write('    "%s"\n' % line)
        out.write(")\n")
    print("wrote preflop_table.py", n, "samples/pair")


if __name__ == "__main__":
    main()
